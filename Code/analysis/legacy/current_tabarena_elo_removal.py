from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import kendalltau, spearmanr

from bencheval.elo_utils import EloHelper


# ============================================================
# PATHS
# ============================================================

# <repo>/Code/analysis/current_tabarena_elo_removal.py
PROJECT_ROOT = Path(__file__).resolve().parents[2]

INPUT_FILE = (
    PROJECT_ROOT
    / "Code"
    / "analysis"
    / "data"
    / "df_results_tabarena_2026_08_13.csv"
)

OUTPUT_DIR = (
    PROJECT_ROOT
    / "Code"
    / "analysis"
    / "results"
    / "dataset_removal_elo"
)

OUTPUT_FILE = OUTPUT_DIR / "elo_dataset_removal_results.csv"


# ============================================================
# TABARENA COLUMNS
# ============================================================

METHOD_COL = "method"
DATASET_COL = "dataset"
ERROR_COL = "metric_error"
SPLIT_COL = "fold"


# ============================================================
# ELO SETTINGS
# ============================================================

INIT_RATING = 1000
SCALE = 400


# ============================================================
# ELO
# ============================================================

def compute_elo(df: pd.DataFrame) -> tuple[pd.Series, pd.DataFrame]:
    """
    Compute the TabArena MLE Elo ranking using bencheval's EloHelper.

    Returns
    -------
    ratings:
        Elo ratings sorted descending.
    battles:
        Battle table generated by EloHelper.
    """

    helper = EloHelper(
        method_col=METHOD_COL,
        task_col=DATASET_COL,
        error_col=ERROR_COL,
        split_col=SPLIT_COL,
    )

    battles = helper.convert_results_to_battles(df)

    ratings = helper.compute_mle_elo(
        battles=battles,
        SCALE=SCALE,
        INIT_RATING=INIT_RATING,
    )

    return ratings, battles


# ============================================================
# RANKING COMPARISON
# ============================================================

def compare_rankings(
    full_ratings: pd.Series,
    reduced_ratings: pd.Series,
) -> dict:

    # Ranking positions
    full_rank = full_ratings.rank(
        ascending=False,
        method="min",
    )

    reduced_rank = reduced_ratings.rank(
        ascending=False,
        method="min",
    )

    # Only compare methods present in both rankings
    common_methods = full_rank.index.intersection(
        reduced_rank.index
    )

    full_rank = full_rank.loc[common_methods]
    reduced_rank = reduced_rank.loc[common_methods]

    # Rank correlations
    kendall = kendalltau(
        full_rank,
        reduced_rank,
    )

    spearman = spearmanr(
        full_rank,
        reduced_rank,
    )

    # Absolute rank movement
    rank_change = (
        reduced_rank - full_rank
    ).abs()

    # Winner
    full_winner = full_ratings.index[0]
    reduced_winner = reduced_ratings.index[0]

    return {
        "full_winner": full_winner,
        "winner_after_removal": reduced_winner,

        "winner_changed": (
            full_winner != reduced_winner
        ),

        "kendall_tau": float(
            kendall.statistic
        ),

        "kendall_p": float(
            kendall.pvalue
        ),

        "spearman_rho": float(
            spearman.statistic
        ),

        "spearman_p": float(
            spearman.pvalue
        ),

        "n_methods": len(common_methods),

        "n_changed_ranks": int(
            (rank_change > 0).sum()
        ),

        "max_rank_change": float(
            rank_change.max()
        ),

        "mean_abs_rank_change": float(
            rank_change.mean()
        ),

        "sum_abs_rank_change": float(
            rank_change.sum()
        ),
    }


# ============================================================
# MAIN
# ============================================================

def main() -> None:

    print("=" * 72)
    print("TABARENA ELO DATASET REMOVAL ANALYSIS")
    print("=" * 72)

    print()
    print(f"Project root : {PROJECT_ROOT}")
    print(f"Input file   : {INPUT_FILE}")
    print(f"Output file  : {OUTPUT_FILE}")
    print()

    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Input file does not exist:\n{INPUT_FILE}"
        )

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # LOAD
    # --------------------------------------------------------

    df = pd.read_csv(INPUT_FILE)

    required_columns = {
        METHOD_COL,
        DATASET_COL,
        ERROR_COL,
        SPLIT_COL,
    }

    missing = (
        required_columns
        - set(df.columns)
    )

    if missing:
        raise ValueError(
            "Missing required columns: "
            f"{sorted(missing)}"
        )

    datasets = (
        df[DATASET_COL]
        .dropna()
        .unique()
    )

    print(f"Rows      : {len(df):,}")
    print(f"Datasets  : {len(datasets)}")
    print(
        f"Methods   : "
        f"{df[METHOD_COL].nunique()}"
    )

    print()

    # --------------------------------------------------------
    # FULL BENCHMARK
    # --------------------------------------------------------

    print(
        "Computing full-benchmark Elo..."
    )

    full_ratings, full_battles = compute_elo(df)

    print(
        f"Full battle table: "
        f"{len(full_battles):,} rows"
    )

    print()

    print("Full benchmark top 10:")
    print(
        pd.DataFrame(
            {
                "rank": np.arange(
                    1,
                    min(10, len(full_ratings)) + 1,
                ),
                "method": full_ratings.head(10).index,
                "elo": full_ratings.head(10).values,
            }
        ).to_string(index=False)
    )

    print()

    # --------------------------------------------------------
    # REMOVE EACH DATASET
    # --------------------------------------------------------

    results = []

    for i, dataset in enumerate(
        datasets,
        start=1,
    ):

        print(
            f"[{i:02d}/{len(datasets)}] "
            f"Removing: {dataset}"
        )

        reduced_df = df[
            df[DATASET_COL] != dataset
        ].copy()

        reduced_ratings, reduced_battles = (
            compute_elo(reduced_df)
        )

        comparison = compare_rankings(
            full_ratings,
            reduced_ratings,
        )

        # ----------------------------------------------------
        # Elo movement of the original winner
        # ----------------------------------------------------

        original_winner = (
            full_ratings.index[0]
        )

        if original_winner in reduced_ratings.index:

            original_winner_elo_after = float(
                reduced_ratings.loc[
                    original_winner
                ]
            )

            original_winner_elo_delta = (
                original_winner_elo_after
                - float(
                    full_ratings.loc[
                        original_winner
                    ]
                )
            )

        else:

            original_winner_elo_after = np.nan
            original_winner_elo_delta = np.nan

        # ----------------------------------------------------
        # Save result
        # ----------------------------------------------------

        results.append(
            {
                "removed_dataset": dataset,

                "n_datasets_remaining": (
                    reduced_df[DATASET_COL]
                    .nunique()
                ),

                "n_battles_after_removal": (
                    len(reduced_battles)
                ),

                "full_winner": (
                    full_ratings.index[0]
                ),

                "full_winner_elo": float(
                    full_ratings.iloc[0]
                ),

                "winner_after_removal": (
                    reduced_ratings.index[0]
                ),

                "winner_after_removal_elo": float(
                    reduced_ratings.iloc[0]
                ),

                "full_winner_elo_after_removal": (
                    original_winner_elo_after
                ),

                "full_winner_elo_delta": (
                    original_winner_elo_delta
                ),

                **comparison,
            }
        )

    # --------------------------------------------------------
    # DATAFRAME
    # --------------------------------------------------------

    results_df = pd.DataFrame(
        results
    )

    # Sort most influential datasets first.
    #
    # Winner changes first,
    # then lowest Kendall tau,
    # then largest rank movement.
    results_df = results_df.sort_values(
        by=[
            "winner_changed",
            "kendall_tau",
            "max_rank_change",
            "mean_abs_rank_change",
        ],
        ascending=[
            False,
            True,
            False,
            False,
        ],
    ).reset_index(drop=True)

    # --------------------------------------------------------
    # SAVE
    # --------------------------------------------------------

    results_df.to_csv(
        OUTPUT_FILE,
        index=False,
    )

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    print()
    print("=" * 72)
    print("SUMMARY")
    print("=" * 72)

    winner_changes = int(
        results_df["winner_changed"].sum()
    )

    print(
        f"Dataset removals : "
        f"{len(results_df)}"
    )

    print(
        f"Winner changes   : "
        f"{winner_changes}"
    )

    print(
        f"Mean Kendall tau : "
        f"{results_df['kendall_tau'].mean():.4f}"
    )

    print(
        f"Min Kendall tau  : "
        f"{results_df['kendall_tau'].min():.4f}"
    )

    print(
        f"Mean max rank change : "
        f"{results_df['max_rank_change'].mean():.2f}"
    )

    print(
        f"Maximum rank change  : "
        f"{results_df['max_rank_change'].max():.0f}"
    )

    print()

    print(
        "Most influential dataset removals:"
    )

    display_columns = [
        "removed_dataset",
        "winner_changed",
        "kendall_tau",
        "spearman_rho",
        "max_rank_change",
        "mean_abs_rank_change",
        "full_winner",
        "winner_after_removal",
    ]

    print(
        results_df[
            display_columns
        ]
        .head(15)
        .to_string(index=False)
    )

    print()
    print(
        f"Saved to:\n{OUTPUT_FILE}"
    )
    print("=" * 72)


if __name__ == "__main__":
    main()