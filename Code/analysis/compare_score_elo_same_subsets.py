def build_same_subset_comparison(
    score_rows: pd.DataFrame,
    elo_rows: pd.DataFrame,
) -> pd.DataFrame:

    score = score_rows.copy()
    elo = elo_rows.copy()

    score = score.rename(
        columns={
            "kendall_tau": "score_kendall_tau",
            "max_rank_change": "score_max_rank_change",
            "mean_rank_change": "score_mean_rank_change",
            "winner": "score_winner",
            "winner_changed": "score_winner_changed",
            "tau_unstable": "score_tau_unstable",
        }
    )

    elo = elo.rename(
        columns={
            "kendall_tau": "elo_kendall_tau",
            "max_rank_change": "elo_max_rank_change",
            "mean_rank_change": "elo_mean_rank_change",
            "winner": "elo_winner",
            "winner_changed": "elo_winner_changed",
            "tau_unstable": "elo_tau_unstable",
        }
    )

    keep_score = [
        "subset_key",
        "removed_datasets",
        "num_removed",
        "score_kendall_tau",
        "score_max_rank_change",
        "score_mean_rank_change",
        "score_winner",
        "score_winner_changed",
        "score_tau_unstable",
    ]

    keep_elo = [
        "subset_key",
        "elo_kendall_tau",
        "elo_max_rank_change",
        "elo_mean_rank_change",
        "elo_winner",
        "elo_winner_changed",
        "elo_tau_unstable",
    ]

    score = score[keep_score]
    elo = elo[keep_elo]

    comparison = score.merge(
        elo,
        on="subset_key",
        how="inner",
        validate="one_to_one",
    )

    comparison["winner_same"] = (
        comparison["score_winner"]
        == comparison["elo_winner"]
    )

    comparison["winner_change_disagreement"] = (
        comparison["score_winner_changed"]
        != comparison["elo_winner_changed"]
    )

    comparison["winner_disagreement"] = (
        ~comparison["winner_same"]
    )

    comparison["tau_difference_elo_minus_score"] = (
        comparison["elo_kendall_tau"]
        - comparison["score_kendall_tau"]
    )

    comparison["abs_tau_difference"] = (
        comparison["tau_difference_elo_minus_score"].abs()
    )

    comparison["aggregation_more_stable"] = np.select(
        [
            comparison["tau_difference_elo_minus_score"] > 0,
            comparison["tau_difference_elo_minus_score"] < 0,
        ],
        [
            "Elo",
            "Score",
        ],
        default="Equal",
    )

    comparison["winner_change_pattern"] = np.select(
        [
            (
                comparison["score_winner_changed"]
                & ~comparison["elo_winner_changed"]
            ),
            (
                ~comparison["score_winner_changed"]
                & comparison["elo_winner_changed"]
            ),
            (
                comparison["score_winner_changed"]
                & comparison["elo_winner_changed"]
            ),
        ],
        [
            "score_changes_only",
            "elo_changes_only",
            "both_change",
        ],
        default="neither_changes",
    )

    comparison = comparison.sort_values(
        ["num_removed", "score_kendall_tau"],
        ascending=[True, True],
    ).reset_index(drop=True)

    comparison.insert(
        0,
        "comparison_index",
        np.arange(1, len(comparison) + 1),
    )

    return comparison


