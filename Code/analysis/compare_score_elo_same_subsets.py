def main() -> None:
    print("=" * 78)
    print("TABARENA SCORE VS ELO — SAME-SUBSET COMPARISON + DIAGNOSTICS")
    print("=" * 78)

    print(f"Project root: {PROJECT_ROOT}")
    print()
    print("Score evaluations:")
    print(f"  {SCORE_EVALUATIONS}")
    print("Elo evaluations:")
    print(f"  {ELO_EVALUATIONS}")

    validate_input_file(SCORE_EVALUATIONS)
    validate_input_file(ELO_EVALUATIONS)

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # 1. Select representative subsets independently
    # --------------------------------------------------------

    score_keys, score_selected = collect_representative_subsets(
        SCORE_EVALUATIONS,
        "Score",
    )

    elo_keys, elo_selected = collect_representative_subsets(
        ELO_EVALUATIONS,
        "Elo",
    )

    shared_keys = score_keys & elo_keys

    print()
    print("=" * 78)
    print("SHARED SUBSET SELECTION")
    print("=" * 78)
    print(f"Score-selected subsets: {len(score_keys)}")
    print(f"Elo-selected subsets:   {len(elo_keys)}")
    print(f"Shared subsets:          {len(shared_keys)}")

    if not shared_keys:
        raise RuntimeError(
            "No shared subsets were found between Score and Elo."
        )

    # --------------------------------------------------------
    # 2. Retrieve only the selected rows
    # --------------------------------------------------------

    score_rows = read_selected_rows(
        SCORE_EVALUATIONS,
        shared_keys,
        "Score",
    )

    elo_rows = read_selected_rows(
        ELO_EVALUATIONS,
        shared_keys,
        "Elo",
    )

    # --------------------------------------------------------
    # 3. Controlled same-subset comparison
    # --------------------------------------------------------

    comparison = build_same_subset_comparison(
        score_rows,
        elo_rows,
    )

    comparison_path = (
        OUTPUT_DIR / "same_subset_comparison.csv"
    )

    comparison.to_csv(
        comparison_path,
        index=False,
    )

    # --------------------------------------------------------
    # 4. Compact summary
    # --------------------------------------------------------

    if not comparison.empty:
        summary = pd.DataFrame(
            [
                {
                    "n_shared_subsets": len(comparison),
                    "mean_score_tau": comparison[
                        "score_kendall_tau"
                    ].mean(),
                    "mean_elo_tau": comparison[
                        "elo_kendall_tau"
                    ].mean(),
                    "mean_elo_minus_score_tau": comparison[
                        "tau_difference_elo_minus_score"
                    ].mean(),
                    "median_elo_minus_score_tau": comparison[
                        "tau_difference_elo_minus_score"
                    ].median(),
                    "score_more_unstable_count": int(
                        (
                            comparison[
                                "tau_difference_elo_minus_score"
                            ]
                            > 0
                        ).sum()
                    ),
                    "elo_more_unstable_count": int(
                        (
                            comparison[
                                "tau_difference_elo_minus_score"
                            ]
                            < 0
                        ).sum()
                    ),
                    "equal_tau_count": int(
                        (
                            comparison[
                                "tau_difference_elo_minus_score"
                            ]
                            == 0
                        ).sum()
                    ),
                    "winner_disagreement_count": int(
                        comparison[
                            "winner_disagreement"
                        ].sum()
                    ),
                    "winner_change_disagreement_count": int(
                        comparison[
                            "winner_change_disagreement"
                        ].sum()
                    ),
                }
            ]
        )
    else:
        summary = pd.DataFrame()

    summary_path = (
        OUTPUT_DIR / "same_subset_summary.csv"
    )

    summary.to_csv(
        summary_path,
        index=False,
    )

    # --------------------------------------------------------
    # 5. Full diagnostics
    # --------------------------------------------------------

    create_diagnostics(comparison)

    # --------------------------------------------------------
    # 6. Console summary
    # --------------------------------------------------------

    print()
    print("=" * 78)
    print("COMPARISON COMPLETE")
    print("=" * 78)

    print(f"Shared subsets: {len(comparison)}")

    if not comparison.empty:
        print(
            f"Mean Score tau: "
            f"{comparison['score_kendall_tau'].mean():.6f}"
        )
        print(
            f"Mean Elo tau:   "
            f"{comparison['elo_kendall_tau'].mean():.6f}"
        )
        print(
            f"Mean Elo-Score: "
            f"{comparison['tau_difference_elo_minus_score'].mean():+.6f}"
        )

        print()
        print("Winner-change pattern:")
        print(
            comparison[
                "winner_change_pattern"
            ].value_counts()
        )

    print()
    print("Saved:")
    print(f"  {comparison_path}")
    print(f"  {summary_path}")
    print(f"  {DIAGNOSTICS_DIR}")


if __name__ == "__main__":
    main()